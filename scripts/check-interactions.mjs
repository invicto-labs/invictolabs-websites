import puppeteer from 'puppeteer-core'
import assert from 'node:assert/strict'
const base = process.argv[2] || 'http://127.0.0.1:4176'
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage()
const errors = [], warnings = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); if (message.type() === 'warn') warnings.push(message.text()) })
const pause = () => new Promise(resolve => setTimeout(resolve, 1200))
try {
  await page.setViewport({ width: 1440, height: 900 })
  await page.goto(base + '/products', { waitUntil: 'networkidle0' })
  await pause()
  const transform = () => page.$eval('.product-tilt-shell', el => getComputedStyle(el).transform)
  const before = await transform()
  await page.$eval('.product-reveal-v3', el => window.scrollTo(0, el.offsetTop + el.offsetHeight - 820))
  await pause()
  assert.notEqual(await transform(), before, 'Product cards must expand on scroll')
  await page.hover('.product-tilt-shell')
  await page.mouse.move(350, 450)
  console.log('PASS product scroll expansion')
  await page.goto(base + '/faq', { waitUntil: 'networkidle0' })
  const faqButton = await page.$('.faq-section button')
  assert.ok(faqButton, 'FAQ button exists')
  const initial = await faqButton.evaluate(el => el.getAttribute('aria-expanded'))
  await faqButton.click()
  assert.notEqual(await faqButton.evaluate(el => el.getAttribute('aria-expanded')), initial)
  console.log('PASS FAQ toggle')
  await page.type('input[name=name]', 'Website QA')
  await page.type('input[name=email]', 'qa@example.com')
  await page.type('input[name=organization]', 'Example testing company')
  await page.type('textarea[name=message]', 'Test draft only. Do not send this inquiry.')
  assert.equal(await page.$eval('.inquiry-form', el => el.checkValidity()), true, 'Inquiry inputs must be valid')
  await page.$eval('.inquiry-form button[type=submit]', el => el.scrollIntoView({ block: 'center', behavior: 'instant' }))
  await pause()
  await page.click('.inquiry-form button[type=submit]')
  await page.waitForSelector('.inquiry-draft')
  assert.match(await page.$eval('.inquiry-draft', el => el.textContent), /not sent/)
  console.log('PASS contact draft (no email sent)')
  await page.setViewport({ width: 390, height: 844 })
  await page.goto(base + '/', { waitUntil: 'networkidle0' })
  await page.click('.menu-toggle')
  assert.equal(await page.$eval('.menu-toggle', el => el.getAttribute('aria-expanded')), 'true')
  await page.click('.primary-nav a[href="/products"]')
  await page.waitForSelector('#products-heading')
  assert.equal(await page.$eval('.menu-toggle', el => el.getAttribute('aria-expanded')), 'false')
  assert.equal(new URL(page.url()).pathname, '/products')
  await page.goBack({ waitUntil: 'networkidle0' })
  await page.waitForSelector('#hero-heading')
  console.log('PASS mobile menu, client navigation and back button')
  console.log(JSON.stringify({ errors, warnings: [...new Set(warnings)] }))
  assert.deepEqual(errors, [])
  assert.deepEqual(warnings, [])
} finally { await browser.close() }
